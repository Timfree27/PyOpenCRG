"""
Creation of synthetic roads.

* :func:`flat_road`: a flat road (straight or with a given heading).
* :func:`from_function`: a road whose height is given by a Python function z(u, v).
* :func:`synthetic_road`: a road described by sections of curvature, slope
  and banking (straight lines, clothoids, circles...).
* :func:`reference_line_from_points` / :func:`road_from_points`: a smooth
  reference line through measured points (GPS, survey...).
* :func:`from_longitudinal_profile`: extrude a 1D profile across the road width.
* :func:`trapezoid_bumps`, :func:`hermite_curve`: building blocks for test tracks.

Example: 120 m straight, 50 m clothoid, then a 50 m radius curve::

    import pyopencrg as crg
    road = crg.generate.synthetic_road(
        length=350, width=4, u_inc=0.1, v_inc=0.1,
        curvature=[(120, 0, 0), (50, 0, -1 / 50), (180, -1 / 50, -1 / 50)],
        slope=[(170, 0, 0), (180, 0, 0.03)],
        banking=[(120, 0, 0), (50, 0, 0.02)],
    )
"""

from __future__ import annotations

import warnings

import numpy as np
from numpy.polynomial import Polynomial

from ._optional import need
from .road import CrgRoad

__all__ = ["flat_road", "from_function", "synthetic_road", "reference_line_from_points",
           "road_from_points", "from_longitudinal_profile", "trapezoid_bumps", "hermite_curve"]


def _count(length, inc, what="length"):
    n = length / inc
    k = int(round(n))
    if abs(n - k) > 1e-6 * max(1.0, n):
        warnings.warn(f"{what} {length} is not a multiple of the increment {inc}: rounded to {k * inc}", stacklevel=3)
    return k


def _v_positions(width, v_inc):
    w = np.atleast_1d(np.asarray(width, dtype=np.float64))
    if w.size == 1:
        lo, hi = -w[0] / 2.0, w[0] / 2.0
    elif w.size == 2:
        lo, hi = w
    else:
        return np.sort(w)
    n = _count(hi - lo, v_inc, "width") + 1
    return lo + np.arange(n) * v_inc


def flat_road(length, width, u_inc=0.01, v_inc=None, heading=0.0, slope=0.0, banking=0.0, comments=None):
    """A flat road.

    Parameters
    ----------
    length : float
        Length (m).
    width : float or (float, float)
        Total width (m, centred on the reference line) or (right, left) edges.
    u_inc, v_inc : float
        Grid increments (m). ``v_inc`` defaults to ``u_inc``.
    heading, slope, banking : float or array
        See :class:`pyopencrg.CrgRoad`.
    """
    v_inc = u_inc if v_inc is None else v_inc
    nu = _count(length, u_inc) + 1
    v = _v_positions(width, v_inc)
    return CrgRoad(np.zeros((nu, v.size)), u_inc, v, heading=heading, slope=slope, banking=banking,
                   comments=comments or ["flat road generated by pyopencrg"])


def from_function(func, length, width, u_inc=0.01, v_inc=None, **kwargs):
    """A road whose grid height is ``func(u, v)``.

    Parameters
    ----------
    func : callable
        Function of two numpy arrays (u, v) returning the heights (m).
    length, width, u_inc, v_inc :
        See :func:`flat_road`.
    **kwargs :
        Passed to :class:`pyopencrg.CrgRoad` (heading, slope, banking...).

    Examples
    --------
    A sine wave road (10 m wavelength, 2 cm amplitude)::

        >>> road = from_function(lambda u, v: 0.02 * np.sin(2 * np.pi * u / 10), 100, 3, 0.05)
    """
    v_inc = u_inc if v_inc is None else v_inc
    nu = _count(length, u_inc) + 1
    v = _v_positions(width, v_inc)
    u = np.arange(nu) * u_inc
    uu, vv = np.meshgrid(u, v, indexing="ij")
    z = np.asarray(func(uu, vv), dtype=np.float64) * np.ones_like(uu)
    kwargs.setdefault("comments", ["road generated by pyopencrg from a function"])
    return CrgRoad(z, u_inc, v, **kwargs)


def _parse_sections(sections, name):
    out = []
    for sec in sections or []:
        if len(sec) == 3 and np.isscalar(sec[1]) and np.isscalar(sec[2]):
            length, a, b = (float(s) for s in sec)
            coeffs = [a, (b - a) / length if length > 0 else 0.0]
        elif len(sec) == 2:
            length = float(sec[0])
            coeffs = [float(c) for c in np.atleast_1d(sec[1])]
        else:
            raise ValueError(f"each {name} section must be (length, start, end) or (length, [c0, c1, ...])")
        if length < 0:
            raise ValueError(f"negative {name} section length")
        out.append((length, coeffs))
    return out


def _eval_sections(sections, nu, inc, integrate, start=0.0, name=""):
    out = np.zeros(nu)
    out[0] = start
    idx = 0
    for length, coeffs in sections:
        n = _count(length, inc, f"{name} section length")
        if idx + n > nu - 1:
            raise ValueError(f"{name} sections are longer than the road")
        t = np.arange(n + 1) * inc
        poly = Polynomial(coeffs)
        if integrate:
            poly = poly.integ(lbnd=0, k=out[idx])
        out[idx:idx + n + 1] = poly(t)
        idx += n
    out[idx + 1:] = out[idx]
    return out


def synthetic_road(length, width, u_inc=0.1, v_inc=None, curvature=None, slope=None, banking=None,
                   heading=0.0, u_start=0.0, z=None):
    """A road described by sections of curvature, slope and banking.

    Each section is either ``(length, start_value, end_value)`` (the value
    changes linearly along the section: a clothoid for the curvature) or
    ``(length, [c0, c1, c2, ...])`` for a polynomial ``c0 + c1 t + c2 t**2 ...``
    of the distance ``t`` from the start of the section. Sections follow
    each other; after the last section the curvature is 0 and the slope and
    banking keep their last value.

    Parameters
    ----------
    length : float
        Length of the road (m).
    width : float or (float, float)
        Width (m) or (right, left) edges.
    u_inc, v_inc : float
        Grid increments (m).
    curvature : list of sections, optional
        Curvature in 1/m (positive = turning left; radius R -> 1/R).
    slope : list of sections, optional
        Longitudinal slope in m/m.
    banking : list of sections, optional
        Banking in m/m.
    heading : float
        Heading at the start (rad).
    u_start : float
        u value of the start.
    z : array_like, optional
        Elevation grid (default: flat).

    Returns
    -------
    CrgRoad
    """
    v_inc = u_inc if v_inc is None else v_inc
    nu = _count(length, u_inc) + 1
    v = _v_positions(width, v_inc)
    comments = ["synthetic road generated by pyopencrg"]
    phi = np.full(nu - 1, float(heading))
    if curvature:
        # heading at the middle of each interval: the chord then follows the arc exactly
        half = _eval_sections(_parse_sections(curvature, "curvature"), 2 * nu - 1, u_inc / 2, True, heading,
                              "curvature")
        phi = half[1::2]
        phi = np.arctan2(np.sin(phi), np.cos(phi))
        comments.append("... curvature added")
    s = 0.0
    if slope:
        s = _eval_sections(_parse_sections(slope, "slope"), nu, u_inc, False, name="slope")[:-1]
        comments.append("... slope added")
    b = 0.0
    if banking:
        b = _eval_sections(_parse_sections(banking, "banking"), nu, u_inc, False, name="banking")
        comments.append("... banking added")
    grid = np.zeros((nu, v.size)) if z is None else np.asarray(z, dtype=np.float64)
    return CrgRoad(grid, u_inc, v, u_start=u_start, heading=phi, slope=s, banking=b, comments=comments)


def reference_line_from_points(x, y, u_inc=0.1, smoothing=None, knot_spacing=2.0):
    """Smooth reference line through measured points.

    The points are first smoothed with a cubic spline (dense points are
    first reduced with a least squares spline with knots every
    ``knot_spacing`` metres), then the line is sampled every ``u_inc``
    metres so that consecutive points are exactly ``u_inc`` apart.

    Parameters
    ----------
    x, y : array_like
        Points along the road, in driving order.
    u_inc : float
        Distance between the points of the result (m).
    smoothing : float in [0, 1], optional
        Smoothing parameter (1 = through the points). Default: chosen from
        the mean point spacing.
    knot_spacing : float
        Knot spacing (m) used to reduce dense point clouds.

    Returns
    -------
    x_ref, y_ref : numpy.ndarray
        Points of the reference line, ``u_inc`` apart.
    """
    make_lsq_spline = need("scipy.interpolate", "reference_line_from_points()").make_lsq_spline

    from .smoothing import smoothing_spline

    x = np.asarray(x, dtype=np.float64).ravel()
    y = np.asarray(y, dtype=np.float64).ravel()
    s = np.concatenate(([0.0], np.cumsum(np.hypot(np.diff(x), np.diff(y)))))
    s, keep = np.unique(s, return_index=True)
    x, y = x[keep], y[keep]
    if s.size < 2:
        raise ValueError("at least 2 distinct points are needed")
    if s.size > 4 and np.mean(np.diff(s)) < 0.25 * knot_spacing:
        nk = max(2, int(np.ceil((s[-1] - s[0]) / knot_spacing)))
        s1 = np.linspace(s[0], s[-1], nk)
        t = np.concatenate(([s[0]] * 4, s1[1:-1], [s[-1]] * 4))
        try:
            sx, sy = make_lsq_spline(s, x, t, k=3), make_lsq_spline(s, y, t, k=3)
            x, y, s = sx(s1), sy(s1), s1
        except (ValueError, np.linalg.LinAlgError):
            pass
    if smoothing is None:
        smoothing = 1.0 - 1.0 / (1.0 + np.mean(np.diff(s)) ** 3 / 0.6)
    fx = smoothing_spline(s, x, smoothing)
    fy = smoothing_spline(s, y, smoothing)
    return _walk(fx, fy, s[0], s[-1], u_inc)


def _walk(fx, fy, s0, se, inc):
    """Sample a parametric curve with chords of exactly ``inc``, following the curve."""
    r1 = complex(fx(s0), fy(s0))
    xs, ys = [r1.real], [r1.imag]
    s1, ds = s0, inc
    while s1 < se:
        for _ in range(10):
            r2 = complex(fx(s1 + ds), fy(s1 + ds))
            d1 = r2 - r1
            f = inc / abs(d1)
            ds *= f
            if abs(f - 1) < 1e-10:
                break
        p = np.angle(d1)
        r1 = r1 + inc * np.exp(1j * p)
        s1 += ds
        xs.append(r1.real)
        ys.append(r1.imag)
    return np.asarray(xs), np.asarray(ys)


def road_from_points(x, y, width, u_inc=0.1, v_inc=None, smoothing=None, z=None):
    """A flat road whose reference line passes through measured points.

    See :func:`reference_line_from_points` for ``x``, ``y`` and ``smoothing``.
    """
    xr, yr = reference_line_from_points(x, y, u_inc, smoothing)
    v_inc = u_inc if v_inc is None else v_inc
    v = _v_positions(width, v_inc)
    phi = np.arctan2(np.diff(yr), np.diff(xr))
    grid = np.zeros((xr.size, v.size)) if z is None else z
    road = CrgRoad(grid, u_inc, v, heading=phi, x_start=xr[0], y_start=yr[0],
                   comments=["road generated by pyopencrg from reference points"])
    return road


def from_longitudinal_profile(u, z, width, v_inc=0.01, u_inc=None, **kwargs):
    """A road whose cross sections are flat and follow a longitudinal profile.

    Parameters
    ----------
    u : array_like
        Positions along the road (m). They do not need to be evenly spaced.
    z : array_like
        Height at these positions (m).
    width : float or (float, float)
        Width of the road (m) or (right, left) edges.
    v_inc : float
        Lateral increment (m).
    u_inc : float, optional
        Longitudinal increment of the result (default: median spacing of ``u``).
    **kwargs :
        Passed to :class:`pyopencrg.CrgRoad`.
    """
    u = np.asarray(u, dtype=np.float64)
    z = np.asarray(z, dtype=np.float64)
    if u_inc is None:
        u_inc = float(np.median(np.diff(u)))
    n = int(np.floor((u[-1] - u[0]) / u_inc + 1e-9)) + 1
    uu = u[0] + np.arange(n) * u_inc
    prof = np.interp(uu, u, z)
    v = _v_positions(width, v_inc)
    kwargs.setdefault("comments", ["road generated by pyopencrg from a longitudinal profile"])
    return CrgRoad(np.repeat(prof[:, None], v.size, axis=1), u_inc, v, u_start=u[0], **kwargs)


def trapezoid_bumps(u_inc=0.005, length=20.0, bump_length=0.23, gap=0.30, height=0.03,
                    attack_angle=45.0, lead_in=10.0):
    """Longitudinal profile made of a series of trapezoidal bumps.

    Parameters
    ----------
    u_inc : float
        Sampling step (m).
    length : float
        Length covered by the bumps (m).
    bump_length : float
        Length of one bump at its base (m).
    gap : float
        Flat distance between two bumps (m).
    height : float
        Height of the bumps (m).
    attack_angle : float
        Angle of the bump sides (degrees).
    lead_in : float
        Flat length before the first bump (m).

    Returns
    -------
    u, z : numpy.ndarray
        Profile, to be used with :func:`from_longitudinal_profile`.
    """
    ramp = height / np.tan(np.radians(attack_angle))
    if 2 * ramp > bump_length:
        raise ValueError("the bump is too short for this height and attack angle")
    period = bump_length + gap
    n_bumps = int(np.ceil(length / period))
    total = lead_in + n_bumps * period
    u = np.arange(0.0, total + u_inc / 2, u_inc)
    t = np.mod(u - lead_in, period)
    zb = np.minimum.reduce([t / ramp, np.ones_like(t), (bump_length - t) / ramp])
    zb = np.clip(zb, 0.0, 1.0) * height
    zb[u < lead_in] = 0.0
    return u, zb


def hermite_curve(p0, p1, t0, t1, n=100):
    """Cubic Hermite curve from point ``p0`` to ``p1`` with tangents ``t0`` and ``t1``.

    Useful to connect two pieces of profile or of reference line smoothly.

    Returns
    -------
    numpy.ndarray of shape (n, 2)
    """
    t = np.linspace(0.0, 1.0, n)[:, None]
    p0, p1, t0, t1 = (np.asarray(a, dtype=np.float64) for a in (p0, p1, t0, t1))
    return ((2 * t ** 3 - 3 * t ** 2 + 1) * p0 + (t ** 3 - 2 * t ** 2 + t) * t0
            + (-2 * t ** 3 + 3 * t ** 2) * p1 + (t ** 3 - t ** 2) * t1)
